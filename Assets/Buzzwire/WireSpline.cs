    public float wireRadius = 0.05f; //debljina zice

    //racuna koja je od onih gore 251 tocke najbliza
    public Vector3 GetClosestPoint(Vector3 position)
    {
        Vector3 closest = points[0];
        float minDist = float.MaxValue;

        for (int i = 0; i < points.Length - 1; i++)
        {
            Vector3 a = transform.TransformPoint(points[i]);
            Vector3 b = transform.TransformPoint(points[i + 1]);
            Vector3 candidate = ClosestPointOnSegment(a, b, position);
            float dist = Vector3.Distance(position, candidate);

            if (dist < minDist)
            {
                minDist = dist;
                closest = candidate;
            }
        }
        return closest;
    }

    Vector3 ClosestPointOnSegment(Vector3 a, Vector3 b, Vector3 p)
    {
        Vector3 ab = b - a;
        float t = Vector3.Dot(p - a, ab) / Vector3.Dot(ab, ab);
        return a + Mathf.Clamp01(t) * ab;
    }

